#!/usr/bin/env python3
"""Write the prompts of the requirement-level rubric judge for the UI.

A Bewertungsbogen whose steps list requirements is graded per requirement
(``LLMJudgeEvaluator.bind_task_rubric``). That lane owns its prompts
(``ml_evaluation/checklist_scoring.py``): the grading template a project
stores for the rubric judge is not used there. The project page shows the
prompts a judge reads, and the API process cannot import worker modules, so
the fixed texts are written to ``services/shared/rubric_requirement_prompts.json``
and served from there (``rubric_judge_prompts.requirement_judge_prompts``).

    python services/workers/scripts/write_rubric_requirement_prompts.py          # write the file
    python services/workers/scripts/write_rubric_requirement_prompts.py --check  # exit 1 when it is stale

``tests/test_requirement_judging.py`` fails when the file and the worker
code disagree, so the file can never show another prompt than the one sent.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

WORKERS = Path(__file__).resolve().parents[1]
TARGET = WORKERS.parent / "shared" / "rubric_requirement_prompts.json"
NOTE = (
    "Generated by services/workers/scripts/write_rubric_requirement_prompts.py from "
    "services/workers/ml_evaluation/checklist_scoring.py. Do not edit: change the worker code and run the script."
)


def document() -> dict:
    """The prompts as the worker assembles them, for a sheet with other
    solution paths (``paths_rule`` is the one rule a sheet without them does
    not get)."""
    for path in (WORKERS, TARGET.parent):  # the worker package and /shared, as in the worker
        if str(path) not in sys.path:
            sys.path.insert(0, str(path))
    from ml_evaluation import checklist_scoring as scoring
    from ml_evaluation.llm_judge_evaluator import (
        RUBRIC_REQUIREMENT_UNIT,
        RUBRIC_REQUIREMENT_UNITS,
    )

    alternatives = "branch"  # the lane's fixed choice, see bind_task_rubric
    paths_rule = scoring._alternatives_rule(alternatives, True)
    assert len(paths_rule) == 1, paths_rule
    return {
        "note": NOTE,
        "default_unit": RUBRIC_REQUIREMENT_UNIT,
        "alternatives": alternatives,
        "user_template": scoring.USER_TEMPLATE,
        "paths_rule": paths_rule[0],
        "units": {
            unit: {
                "system_prompt": scoring.system_prompt(unit, alternatives, True),
                "closing_rules": scoring.closing_rules(unit, alternatives, True),
            }
            for unit in RUBRIC_REQUIREMENT_UNITS
        },
    }


def rendered() -> str:
    return json.dumps(document(), ensure_ascii=False, indent=2) + "\n"


def main(argv: list[str]) -> int:
    text = rendered()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is stale: run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
