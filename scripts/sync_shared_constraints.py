#!/usr/bin/env python3
"""Keep the shared dependency bounds of services/api and services/workers in step.

services/shared/dependency-constraints.txt is the single source of the bounds
for every package the shared code relies on. uv reads constraints only from
`[tool.uv] constraint-dependencies` in a project's pyproject.toml, and each
service is its own Docker build context, so the list is copied into both
pyproject.toml files between generated markers.

    python3 scripts/sync_shared_constraints.py          # rewrite both blocks
    python3 scripts/sync_shared_constraints.py --check  # CI: fail on drift

--check fails when
  * a pyproject block differs from the constraints file, or
  * services/api/uv.lock and services/workers/uv.lock resolve a package both
    images install (direct or transitive, test-only packages excluded) to
    different versions. One version
    per package across both images is the point of the shared list: when
    this fires, tighten the bound in the constraints file and re-lock.

Standard library only, so the CI lint job can run it without installs.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import tomllib

ROOT = Path(__file__).resolve().parent.parent
CONSTRAINTS = ROOT / "services" / "shared" / "dependency-constraints.txt"
SERVICES = ("api", "workers")

BEGIN = "# BEGIN shared constraints (generated by scripts/sync_shared_constraints.py, do not edit)"
END = "# END shared constraints"
BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)


def read_constraints() -> list[str]:
    lines = []
    for raw in CONSTRAINTS.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            lines.append(line)
    return lines


def render_block(constraints: list[str]) -> str:
    body = "\n".join(f'    "{c}",' for c in constraints)
    return f"{BEGIN}\nconstraint-dependencies = [\n{body}\n]\n{END}"


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def locked_runtime_versions(service: str) -> dict[str, str]:
    """Versions of the packages a service's image installs (`--no-dev`).

    Walks the lock from the project's runtime dependencies, so test extras
    and dependency groups (pytest and friends) are not compared: they never
    run the shared code in production.
    """
    lock = ROOT / "services" / service / "uv.lock"
    packages: dict[str, list[dict]] = {}
    root = None
    for pkg in tomllib.loads(lock.read_text()).get("package", []):
        packages.setdefault(normalize(pkg["name"]), []).append(pkg)
        if "virtual" in pkg.get("source", {}) or "editable" in pkg.get("source", {}):
            root = pkg
    if root is None:
        raise SystemExit(f"{lock.relative_to(ROOT)}: project entry not found")

    versions: dict[str, set[str]] = {}
    seen: set[tuple[str, str]] = set()
    todo = [(d["name"], tuple(d.get("extra", ()))) for d in root.get("dependencies", [])]
    while todo:
        name, extras = todo.pop()
        name = normalize(name)
        for extra in ("",) + extras:
            if (name, extra) in seen:
                continue
            seen.add((name, extra))
            # A name can be locked more than once under platform markers
            # (torch for darwin vs linux); every entry counts.
            for pkg in packages.get(name, []):
                if extra:
                    deps = pkg.get("optional-dependencies", {}).get(extra, [])
                else:
                    deps = pkg.get("dependencies", [])
                    versions.setdefault(name, set()).add(pkg.get("version", "?"))
                todo.extend((d["name"], tuple(d.get("extra", ()))) for d in deps)
    return {name: ", ".join(sorted(v)) for name, v in versions.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift instead of rewriting")
    args = parser.parse_args()

    block = render_block(read_constraints())
    problems: list[str] = []

    for service in SERVICES:
        path = ROOT / "services" / service / "pyproject.toml"
        text = path.read_text()
        match = BLOCK_RE.search(text)
        if match is None:
            problems.append(f"{path.relative_to(ROOT)}: no generated constraints block under [tool.uv]")
            continue
        if match.group(0) == block:
            continue
        if args.check:
            problems.append(
                f"{path.relative_to(ROOT)}: constraint block is out of date "
                "(run python3 scripts/sync_shared_constraints.py, then uv lock)"
            )
        else:
            path.write_text(text[: match.start()] + block + text[match.end() :])
            print(f"updated {path.relative_to(ROOT)}")

    if args.check:
        api, workers = (locked_runtime_versions(s) for s in SERVICES)
        for name in sorted(api.keys() & workers.keys()):
            if api[name] != workers[name]:
                problems.append(
                    f"{name}: api locks {api[name]}, workers lock {workers[name]} "
                    "(bound it in services/shared/dependency-constraints.txt and re-lock)"
                )

    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
